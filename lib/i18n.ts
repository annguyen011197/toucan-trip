const DICT: Record<Lang, Record<MessageKey, string>> = { en, vi };

export type Translate = (key: MessageKey, vars?: Record<string, string | number>) => string;

export function translator(lang: Lang): Translate {
  return (key, vars) => {
    const s = DICT[lang][key] ?? en[key] ?? key;
    return vars ? s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m)) : s;
  };
}

/** For data-driven keys (interest/diet labels): falls back to the raw value when there's no entry. */
export function label(lang: Lang, prefix: "interest" | "diet", value: string): string {
  return DICT[lang][`${prefix}.${value}` as MessageKey] ?? value;
}

export function detectLang(): Lang {
  if (typeof navigator === "undefined") return "en";
  return navigator.language?.toLowerCase().startsWith("vi") ? "vi" : "en";
}
